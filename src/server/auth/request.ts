// Small helpers for the cookie-setting route handlers.

/** The caller's IP as the platform reports it (Vercel overwrites x-forwarded-for, so it cannot be spoofed there). */
export function clientIp(headers: Headers): string {
  const forwarded = headers.get("x-forwarded-for")?.split(",")[0]?.trim();
  const ip = forwarded || headers.get("x-real-ip")?.trim() || "unknown";
  return ip.slice(0, 64);
}

/** True only when the browser says the request came from this same site. A missing Origin is refused. */
export function isSameOrigin(headers: Headers): boolean {
  const origin = headers.get("origin");
  const host = headers.get("host");
  if (!origin || !host) return false;
  try {
    return new URL(origin).host === host;
  } catch {
    return false;
  }
}
